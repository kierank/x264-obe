/* cc -o la8corr tools/la8corr.c -lm && ./la8corr > encoder/lookahead8corr.h
 *
 * The 8-bit lookahead's lowres cost correction c' = c - round( F*exp( -c/K ) )
 * for c >= T, else c: F, K fitted on rack01 LA8FIT2, mean-matching, 5 clips, T on
 * LA8FIT3, 11 clips. A table per group runs from c = 0 to the first c whose
 * correction rounds to 0; round is floor( x + 0.5 ). */

#include <stdio.h>
#include <math.h>

static const struct { const char *name, *macro; double f, k; int t; } groups[3] =
{
    { "intra", "INTRA", 7.816,  1204.6, 33 },
    { "p",     "P",     12.891, 273.19, 34 },
    { "b",     "B",     14.804, 403.45, 32 },
};

int main( void )
{
    printf( "/* Generated by tools/la8corr.c, do not edit.\n"
            " * The 8-bit lookahead's lowres cost correction c' = c - round( F*exp( -c/K ) ) for c >= T,\n"
            " * else c: F, K fitted on rack01 LA8FIT2, mean-matching, 5 clips, T on LA8FIT3, 11 clips:\n"
            " * la8_corr_<group>[min( c, LA8_CORR_<GROUP>_MAX )]. */\n" );
    for( int g = 0; g < 3; g++ )
    {
        int n = 0;
        while( floor( groups[g].f * exp( -n / groups[g].k ) + 0.5 ) > 0 )
            n++;
        printf( "\n/* %s: F %g, K %g, T %d */\n#define LA8_CORR_%s_MAX %d\nstatic const uint8_t la8_corr_%s[LA8_CORR_%s_MAX+1] =\n{",
                groups[g].name, groups[g].f, groups[g].k, groups[g].t, groups[g].macro, n, groups[g].name, groups[g].macro );
        for( int c = 0; c <= n; c++ )
            printf( "%s%d%s", c % 32 ? "" : "\n    ",
                    c < groups[g].t ? 0 : (int)floor( groups[g].f * exp( -c / groups[g].k ) + 0.5 ),
                    c < n ? "," : "\n" );
        printf( "};\n" );
    }
    return 0;
}
