    cmp      r6d, 63
    je .skip_last_sigmap
%if notcpuflag(avx512icl)
; x264_cabac_encode_decision( cb, ctx_sig + sig_off[last], 1 )
    movzx    r1d, byte [r4+r6]
    movzx    r2d, byte [r5+r1]
    movzx   r10d, byte [cabac_transition+1+r2*2 GLOBAL]
