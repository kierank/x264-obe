; 4x4 blocks, avx2: each sig and last context is used at most once per block and
; the sig, last and level context ranges are disjoint, so the kinds are coded one
; after the other: the sig flags of every i < last without a branch on l[i]
; (bt/adc gives 2*state+bin), then last flag and level of the nonzero ones,
; descending. f8_bits is an integer sum.
%macro CABAC_RESIDUAL_RD_4x4_AVX2 0
    %assign rd4_stack (17*SIZEOF_DCTCOEF+15) & ~15
%ifdef PIC
    cglobal cabac_block_residual_rd_internal, 4,12,3,-rd4_stack
    lea     r11, [$$]
    %define GLOBAL +r11-$$
%else
    cglobal cabac_block_residual_rd_internal, 4,11,3,-rd4_stack
    %define GLOBAL
%endif
    RD_TMP_REGS 4, 5, 10
    %define dct rsp+SIZEOF_DCTCOEF
    %define rd_bl RD4_AVX2_BRANCHLESS
; abs() of the aligned block, l[0] at dct
    mov      r4, r0
    and     r4d, SIZEOF_DCTCOEF
    neg      r4
    pabsw    m0, [r0+r4+0*mmsize]
    pabsw    m1, [r0+r4+1*mmsize]
    movu [rsp+r4+SIZEOF_DCTCOEF+0*mmsize], m0
    movu [rsp+r4+SIZEOF_DCTCOEF+1*mmsize], m1
    packsswb m0, m1
    pxor     m2, m2
    pcmpeqb  m0, m2
    pmovmskb r9d, m0
    not      r9d
    and      r9d, [rd_nzmask_4x4+r2*8 GLOBAL]
    mov      r6d, [rd_nzmask_4x4+r2*8+4 GLOBAL]
    shrx     r9d, r9d, r6d                                    ; bit i = l[i] != 0
    lzcnt    r6d, r9d
    xor      r6d, 31                                          ; r6 = last
    shl      r1d, 4                                           ; MB_INTERLACED*16
    add      r1d, r2d
    movzx    r5d, word [significant_coeff_flag_offset+r1*2 GLOBAL]    ; r5 = ctx_sig
    movzx    r7d, word [last_coeff_flag_offset+r1*2 GLOBAL]           ; r7 = ctx_last
    movzx    r8d, word [coeff_abs_level_m1_offset+r2*2 GLOBAL]        ; r8 = ctx_level
    mov      r0d, [r3+cb.bits_encoded]                        ; r0 = cabac.f8_bits_encoded
    add       r3, cb.state
    add       r5, r3
    add       r7, r3
    add       r8, r3
; if( last != count_cat_m1[ctx_block_cat] ): sig and last flags of last, bin 1
    cmp      r6b, [count_cat_m1+r2 GLOBAL]
    je .skip_last_sigmap
    movzx    r1d, byte [r5+r6]
    mov      r1d, [rd_sig_tab+4+r1*8 GLOBAL]
    mov [r5+r6], r1b
    shr      r1d, 16
    add      r0d, r1d
    movzx    r1d, byte [r7+r6]
    mov      r1d, [rd_sig_tab+4+r1*8 GLOBAL]
    mov [r7+r6], r1b
    shr      r1d, 16
    add      r0d, r1d
.skip_last_sigmap:
; sig flags of i < last; r10d: entropy sum << 16 over the transitions, < 16*1469 and 16*127
    xor     r10d, r10d
    lea      r1d, [r6-1]
    test     r6d, r6d
    jz .sig_end
.sig_loop:
    movzx    r2d, byte [r5+r1]
    bt       r9d, r1d
    adc      r2d, r2d                                         ; 2*state+bin
    mov      r2d, [rd_sig_tab+r2*4 GLOBAL]
    mov [r5+r1], r2b
    add     r10d, r2d
    dec      r1d
    jge .sig_loop
    shr     r10d, 16
    add      r0d, r10d
.sig_end:
; levels: last, then the nonzero coefficients below last with last flag 0
    LOAD_DCTCOEF r1d
    COEFF_ABS_LEVEL_AVX2 last, 1
    btr      r9d, r6d
    test     r9d, r9d
    jz .end
.coeff_loop:
    lzcnt    r6d, r9d
    xor      r6d, 31
    btr      r9d, r6d
    movzx    r4d, byte [r7+r6]
    movzx    r5d, byte [cabac_transition+r4*2 GLOBAL]
    movzx    r4d, word [cabac_entropy+r4*2 GLOBAL]
    mov [r7+r6], r5b
    add      r0d, r4d
    LOAD_DCTCOEF r1d
    COEFF_ABS_LEVEL_AVX2 coeff, 0
    test     r9d, r9d
    jnz .coeff_loop
.end:
    mov [r3+cb.bits_encoded-cb.state], r0d
    RET
    COEFF_ABS_LEVEL_AVX2_ESCAPE last, 1
    COEFF_ABS_LEVEL_AVX2_ESCAPE coeff, 0
%endmacro

; rd 8x8 level pass helpers (8-bit). r0d = f8_bits.
; n zeros (%3 = rd8_last) or n zeros then a one (%3 = rd8_zero1) on the state
; in r%1, n in r%2 (clobbered), any n; runs over 16 go out of line (.%5_long)
%macro RD8_RUN 5 ; state, n, table, tmp, label
    cmp     r%2d, 16
    ja .%5_long
.%5_back:
    shl     r%2d, 7
    add     r%2d, r%1d
    movzx   r%1d, byte [%3_pow+r%2 GLOBAL]
    movzx   r%2d, word [%3_bits+r%2*2 GLOBAL]
    add      r0d, r%2d
%endmacro

%macro RD8_RUN_LONG 5
.%5_long:
    movzx   r%4d, word [rd8_last_bits+16*256+r%1*2 GLOBAL]
    movzx   r%1d, byte [rd8_last_pow+16*128+r%1 GLOBAL]
    add      r0d, r%4d
    sub     r%2d, 16
    cmp     r%2d, 16
    ja .%5_long
    jmp .%5_back
%endmacro

; unary suffix of a level > 1: abs in r1d (clobbered), gt1 state in r%1, r4 clobbered
%macro RD8_GT1 2 ; state, label
    cmp      r1d, 15
    jae .%2_esc
    shl      r1d, 7
    add      r1d, r%1d
    movzx   r%1d, byte [cabac_transition_unary-128+r1 GLOBAL]
    movzx    r1d, word [cabac_size_unary-256+r1*2 GLOBAL]
    add      r0d, r1d
.%2_esc_back:
%endmacro

%macro RD8_GT1_ESC 2
.%2_esc:
    movzx    r4d, word [cabac_size_unary+256*14+r%1*2 GLOBAL]
    movzx   r%1d, byte [cabac_transition_unary+128*14+r%1 GLOBAL]
    add      r0d, r4d
    sub      r1d, 14
    lzcnt    r4d, r1d
    xor      r4d, 0x1f
    shl      r4d, 9                                           ; bs_size_ue_big(abs-15)<<8
    lea      r0d, [r0+r4+256]
    jmp .%2_esc_back
%endmacro

; last flag (bin 0) of the nonzero coefs below last in last context %1:
; n = popcnt of the positions of the context, one rd8_last_pow step
%macro RD8_LAST0 3 ; context, mask source, mask
    mov      r3d, %2
    and      r3d, %3
    popcnt   r3d, r3d
    shl      r3d, 7
    movzx    r4d, byte [r7+%1]
    add      r3d, r4d
    movzx    r4d, byte [rd8_last_pow+r3 GLOBAL]
    mov [r7+%1], r4b
    movzx    r4d, word [rd8_last_bits+r3*2 GLOBAL]
    add      r0d, r4d
%endmacro

; level1 context %1 (1-3) of phase A: one bin 0 if nA (r3d) >= %1
%macro RD8_PHASEA 1
    xor      r2d, r2d
    cmp      r3d, %1
    setae    r2b
    shl      r2d, 7
    movzx    r1d, byte [r8+%1]
    add      r2d, r1d
    movzx    r1d, byte [rd8_last_pow+r2 GLOBAL]
    mov [r8+%1], r1b
    movzx    r1d, word [rd8_last_bits+r2*2 GLOBAL]
    add      r0d, r1d
%endmacro

; the next level > 1 below F, descending: its run of level-1 coefs and its own
; bin on level1 context 0 (r5), then its unary suffix on gt1 context %1 (memory)
; or, %3 = 1, on the gt1 state in r6. Exit to .%4 when there is none.
%macro RD8_GT1_NEXT 4 ; gt1 context, label, state in r6, exit
    test     r12, r12
    jz .%4
    lzcnt    r2, r12
    xor      r2d, 63                                          ; p
    btr      r12, r2
    lea      r4d, [r2+1]
    shrx     r3, r10, r4
    popcnt   r3, r3                                           ; level-1 coefs between p and the previous one
    bzhi     r10, r10, r2
    RD8_RUN  5, 3, rd8_zero1, 1, %2
    movzx    r1d, word [dct+r2*2]
%if %3 == 0
    movzx    r6d, byte [r8+%1]
%endif
    RD8_GT1  6, %2
%if %3 == 0
    mov [r8+%1], r6b
%endif
%endmacro

; levels and last flags below last of the rd 8x8 kernels. In: r0d f8_bits, r6
; last, r7 ctx_last, r8 ctx_level, r9 nonzero mask, r12 mask of levels > 1, the
; abs() copy at dct. Clobbers r1-r6, r9, r10, r12.
; Each context's decisions keep the descending order of the C code; contexts
; are coded one after another (disjoint, f8_bits is an integer sum):
; - last flags: all bin 0, so one n-step per context;
; - phase A, the level-1 coefs above F (the highest level > 1), nA of them: one
;   bin 0 each on level1 contexts 1, 2, 3, then nA-3 on context 4; F's bin 1 on
;   context min(nA,3)+1, its unary on gt1 context 5;
; - below F the level1 context is 0: a run of bin 0 then bin 1 per level > 1
;   (rd8_zero1), whose unary goes to gt1 context 5+min(i,4), then a final run.
; The loop is over the levels > 1, so level-1 coefs cost no branch.
%macro RD8_LEVELS 0
; last flags
    mov       r1, r9
    btr       r1, r6
    mov       r2, r1
    shr       r2, 32
    RD8_LAST0 0, r1d, 1
    RD8_LAST0 1, r1d, 0xfffe
    RD8_LAST0 2, r1d, 0xffff0000
    test     r2d, r2d
    jz .last_hi_end                                           ; no nonzero coef in 32-62
    RD8_LAST0 3, r2d, 0xff
    RD8_LAST0 4, r2d, 0xff00
    RD8_LAST0 5, r2d, 0xf0000
    RD8_LAST0 6, r2d, 0xf00000
    RD8_LAST0 7, r2d, 0xf000000
    RD8_LAST0 8, r2d, 0xf0000000
.last_hi_end:
; signs of the level-1 coefs (the unary sizes hold those of the others)
    popcnt    r3, r9                                          ; N
    popcnt    r4, r12
    neg       r4
    add       r4, r3
    shl      r4d, 8
    add      r0d, r4d
    lzcnt     r1, r12
    mov      r4d, 64
    sub      r4d, r1d                                         ; F+1, 0 if no level > 1
    bzhi     r10, r9, r4                                      ; nonzero at F and below
    popcnt    r2, r10
    sub      r3d, r2d                                         ; nA
    RD8_PHASEA 1
    RD8_PHASEA 2
    RD8_PHASEA 3
    lea      r2d, [r3-3]
    xor      r1d, r1d
    test     r2d, r2d
    cmovs    r2d, r1d
    movzx    r5d, byte [r8+4]
    RD8_RUN  5, 2, rd8_last, 1, a4
    mov [r8+4], r5b
    test     r12, r12
    jz .levels_end
; F
    mov      r2d, 3
    cmp      r3d, r2d
    cmovb    r2d, r3d
    movzx    r1d, byte [r8+r2+1]
    mov      r1d, [rd_sig_tab+4+r1*8 GLOBAL]
    mov [r8+r2+1], r1b
    shr      r1d, 16
    add      r0d, r1d
    lea      r2d, [r4-1]                                      ; F
    btr      r10, r2                                          ; nonzero below F
    btr      r12, r2
    movzx    r1d, word [dct+r2*2]
    movzx    r6d, byte [r8+5]
    RD8_GT1  6, f
    mov [r8+5], r6b
; below F
    movzx    r5d, byte [r8]
    RD8_GT1_NEXT 6, g1, 0, levels_tail
    RD8_GT1_NEXT 7, g2, 0, levels_tail
    RD8_GT1_NEXT 8, g3, 0, levels_tail
    movzx    r6d, byte [r8+9]
.g9_loop:
    RD8_GT1_NEXT 9, g9, 1, g9_tail
    jmp .g9_loop
.g9_tail:
    mov [r8+9], r6b
.levels_tail:
    popcnt    r2, r10
    RD8_RUN  5, 2, rd8_last, 1, t
    mov [r8], r5b
.levels_end:
%endmacro

; the out-of-line parts of RD8_LEVELS, after the RET
%macro RD8_LEVELS_TAIL 0
    RD8_RUN_LONG 5, 2, rd8_last, 1, a4
    RD8_RUN_LONG 5, 3, rd8_zero1, 1, g1
    RD8_RUN_LONG 5, 3, rd8_zero1, 1, g2
    RD8_RUN_LONG 5, 3, rd8_zero1, 1, g3
    RD8_RUN_LONG 5, 3, rd8_zero1, 1, g9
    RD8_RUN_LONG 5, 2, rd8_last, 1, t
    RD8_GT1_ESC 6, f
    RD8_GT1_ESC 6, g1
    RD8_GT1_ESC 6, g2
    RD8_GT1_ESC 6, g3
