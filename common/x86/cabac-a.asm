; 8x8 blocks, avx2. The sig pass, for last < RD8_SIG_PAIRS_MIN: as the ssse3
; version (every i < last without a branch on l[i], one rd_sig_tab load per
; flag; r10: entropy sum << 16 over the transitions, 64-bit, the transitions
; < 63*127). Otherwise by pairs: each context's positions, descending, go to
; fixed slots (padded at the front with position 63); a code per position
; (bin, or 2 = not coded: above last or 63) is permuted to the slots by
; vpshufb, pairs give 3*c1+c2 by pmaddubsw, and each context runs its pairs on
; its state in a register: one rd8_sig9 load per pair. Then RD8_LEVELS. The
; ymm abs() gives the nonzero mask and the mask of levels > 1.
%ifndef RD8_SIG_PAIRS_MIN
    %define RD8_SIG_PAIRS_MIN 32
%endif
%macro CABAC_RESIDUAL_RD_8x8_AVX2 0
    %define dct rsp
    %assign rd8_stack 64*SIZEOF_DCTCOEF+mmsize+96 ; abs() copy, cb, sig pairs
    %define cbm [rsp+64*SIZEOF_DCTCOEF]
    %define sigp rsp+64*SIZEOF_DCTCOEF+mmsize
%ifdef PIC
    cglobal cabac_block_residual_8x8_rd_internal, 4,13,8,-rd8_stack
    lea     r11, [$$]
    %define GLOBAL +r11-$$
%else
    cglobal cabac_block_residual_8x8_rd_internal, 4,13,8,-rd8_stack
    %define GLOBAL
%endif
    pabsw     m0, [r0+0*mmsize]
    pabsw     m1, [r0+1*mmsize]
    pabsw     m2, [r0+2*mmsize]
    pabsw     m3, [r0+3*mmsize]
    mova [rsp+0*mmsize], m0
    mova [rsp+1*mmsize], m1
    mova [rsp+2*mmsize], m2
    mova [rsp+3*mmsize], m3
    packsswb  m0, m1                                          ; 0-7 16-23 8-15 24-31, saturated
    packsswb  m2, m3
    pcmpeqb   m1, m0, [pb_1]
    pcmpeqb   m3, m2, [pb_1]
    pxor      m4, m4
    pcmpeqb   m0, m4
    pcmpeqb   m2, m4
    vpermq    m0, m0, q3120
    vpermq    m2, m2, q3120
    vpermq    m1, m1, q3120
    vpermq    m3, m3, q3120
    pmovmskb r9d, m0
    pmovmskb r10d, m2
    shl      r10, 32
    or        r9, r10
    not       r9                                              ; bit i = l[i] != 0
    pmovmskb r12d, m1
    pmovmskb r10d, m3
    shl      r10, 32
    or       r12, r10
    andn     r12, r12, r9                                     ; bit i = abs(l[i]) > 1
    lzcnt     r6, r9
    xor      r6d, 63                                          ; r6 = last
    shl      r1d, 4                                           ; MB_INTERLACED*16
    lea       r4, [significant_coeff_flag_offset_8x8+r1*4 GLOBAL]    ; r4 = sig offset 8x8
    lea     r10d, [r1+r1*2]                                   ; MB_INTERLACED*48
    add      r1d, r2d
    movzx    r5d, word [significant_coeff_flag_offset+r1*2 GLOBAL]    ; r5 = ctx_sig
    movzx    r7d, word [last_coeff_flag_offset+r1*2 GLOBAL]           ; r7 = ctx_last
    movzx    r8d, word [coeff_abs_level_m1_offset+r2*2 GLOBAL]        ; r8 = ctx_level
    mov      r0d, [r3+cb.bits_encoded]                        ; r0 = cabac.f8_bits_encoded
    mov      cbm, r3
    add       r3, cb.state
    add       r5, r3
    add       r7, r3
    add       r8, r3
; if( last != 63 ): last flag of last, bin 1
    cmp      r6d, 63
    je .skip_last_sigmap
    movzx    r1d, byte [last_coeff_flag_offset_8x8+r6 GLOBAL]
    movzx    r2d, byte [r7+r1]
    mov      r2d, [rd_sig_tab+4+r2*8 GLOBAL]
    mov [r7+r1], r2b
    shr      r2d, 16
    add      r0d, r2d
.skip_last_sigmap:
    cmp      r6d, RD8_SIG_PAIRS_MIN
    jae .sig_pairs
; sig flag of last, bin 1 (last < 63 here)
    movzx    r1d, byte [r4+r6]
    movzx    r2d, byte [r5+r1]
    mov      r2d, [rd_sig_tab+4+r2*8 GLOBAL]
    mov [r5+r1], r2b
    shr      r2d, 16
    add      r0d, r2d
; for( int i = last-1 ; i >= 0; i-- ) x264_cabac_encode_decision( cb, ctx_sig + sig_off[i], !!l[i] )
    xor     r10d, r10d
    lea      r1d, [r6-1]
    test     r6d, r6d
    jz .sig_end
.sig_loop:
    movzx    r2d, byte [r4+r1]
    movzx    r3d, byte [r5+r2]
    bt        r9, r1
    adc      r3d, r3d                                         ; 2*state+bin
    mov      r3d, [rd_sig_tab+r3*4 GLOBAL]
    mov [r5+r2], r3b
    add      r10, r3
    dec      r1d
    jge .sig_loop
    shr      r10, 16
    add      r0d, r10d
.sig_end:
    RD8_LEVELS
    mov       r3, cbm
    mov [r3+cb.bits_encoded], r0d
    RET
    RD8_LEVELS_TAIL
.sig_pairs:
; codes: bin (l[i] != 0), or 2 for i > last and i = 63; m0/m2: l[i] == 0 bytes
    vmovd    xm4, r6d
    vpbroadcastb m4, xm4
    movu      m5, [rd8_sig_pos]
    movu      m6, [rd8_sig_pos+32]
    pcmpgtb   m5, m4
    pcmpgtb   m6, m4
    por       m0, m5                                          ; no bin above last, nor at 63 = last
    por       m2, m6
    pandn     m0, [pb_1]
    pandn     m2, [pb_1]
    psubb     m0, m5
    psubb     m2, m6
    psubb     m0, m5
    psubb     m2, m6
    lea      r10, [rd8_sig_perm+r10*8 GLOBAL]                 ; frame or field slots
    vpermq    m1, m0, q3232                                   ; codes 16-31, both lanes
    vpermq    m0, m0, q1010                                   ; codes 0-15
    vpermq    m3, m2, q3232
    vpermq    m2, m2, q1010
%assign %%o 0
%rep 3
    pshufb    m4, m0, [r10+(4*%%o+0)*32]
    pshufb    m5, m1, [r10+(4*%%o+1)*32]
    pshufb    m6, m2, [r10+(4*%%o+2)*32]
    pshufb    m7, m3, [r10+(4*%%o+3)*32]
    por       m4, m5
    por       m6, m7
    por       m4, m6
    pmaddubsw m4, [rd8_sig_pair]                             ; 3*c1+c2 per slot pair
    mova [sigp+%%o*32], m4
%assign %%o %%o+1
%endrep
    xor     r10d, r10d
    RD8_SIG_PAIRS
    shr      r10, 17
    add      r0d, r10d
    jmp .sig_end
%endmacro


; 4:2:2 chroma dc rd, avx2 (ctx_block_cat = DCT_CHROMA_DC, 8 coefficients, sig and
; last contexts 0,0,1,1,2,2,2). The contexts of the sig, last and level flags are
; disjoint and each context's decisions keep the C order, so f8_bits (an integer
; sum) and the states are those of the C.
; - sig/last: per position p <= 6 a sig code (l[p] != 0 for p <= last, else 2:
;   not coded) and a last code (p == last for l[p] != 0, else 2), from a
;   suffix-or of the nonzero bytes. Each context codes its positions in
;   descending order as pairs (3*c1+c2) on its state in a register, one rd8_sig9
;   load per pair: contexts 0 and 1 one pair, context 2 two (6,5 then 4);
;   contexts above last are skipped.
; - levels: per coefficient for fewer than RD422_LEVELS_MIN nonzero coefs, else
;   per level > 1 (as RD8_LEVELS) with the chroma dc gt1 contexts, capped at 8.
;   The unary row min(abs,15)*128 of every coefficient comes from the vector
;   abs(), and the escapes' bs_size_ue_big(abs-15) from the float exponent of
;   abs-14, summed over the block: no branch on the level.
%ifndef RD422_LEVELS_MIN
    %define RD422_LEVELS_MIN 4
%endif

; one context of the sig/last pass: state at [%1+%2], pair code word %3, and for
; context 2 a second pair %4 (its second slot not coded); sum in r10
%macro RD422_CTX 3-4
    movzx    r1d, byte [%1+%2]
    lea      r1d, [r1+r1*8]
    movzx    r2d, word [rd422c+%3*2]
    add      r1d, r2d
    mov      r1d, [rd8_sig9+r1*4 GLOBAL]
    add      r10, r1
%if %0 == 4
    movzx    r1d, r1w
    movzx    r2d, word [rd422c+%4*2]
    add      r1d, r2d
    mov      r1d, [rd8_sig9+8+r1*4 GLOBAL]
    add      r10, r1
%endif
    movzx    r1d, r1w
    imul     r1d, r1d, 57
    shr      r1d, 9                                           ; 9*state' / 9
    mov [%1+%2], r1b
%endmacro

; unary suffix of a level: unary row in r%2 (clobbered), gt1 state in r%1
; (level 1: row 0, the sign alone, state kept)
%macro RD422_UNARY 2
    add     r%2d, r%1d
    movzx   r%1d, byte [cabac_transition_unary-128+r%2 GLOBAL]
    movzx   r%2d, word [cabac_size_unary-256+r%2*2 GLOBAL]
    add      r0d, r%2d
%endmacro

; the next level > 1 below F, descending: its run of level-1 coefs and its own
; bin on level1 context 0 (r5, rd8_zero1), then its unary on gt1 context %1
; (memory) or, %2 = 1, on the gt1 state in r6. Exit to %3 when there is none.
%macro RD422_NEXT 3 ; gt1 context, state in r6, exit
    test    r12d, r12d
    jz %3
    lzcnt    r2d, r12d
    xor      r2d, 31                                          ; p
    btr     r12d, r2d
    lea      r4d, [r2+1]
    shrx     r9d, r10d, r4d
    popcnt   r9d, r9d                                         ; level-1 coefs above p
    bzhi    r10d, r10d, r2d
    shl      r9d, 7
    add      r9d, r5d
    movzx    r5d, byte [rd8_zero1_pow+r9 GLOBAL]
    movzx    r9d, word [rd8_zero1_bits+r9*2 GLOBAL]
    add      r0d, r9d
    movzx    r1d, word [rd422u+r2*2]
%if %2 == 0
    movzx    r6d, byte [r8+%1]
%endif
    RD422_UNARY 6, 1
%if %2 == 0
    mov [r8+%1], r6b
%endif
%endmacro

; one level of the per-coefficient pass: position in r6, level1 context %1 and
; gt1 context %2 (constants, or registers other than r1, r2, r4, r5); out r2d = abs > 1
%macro RD422_LEVEL 2
    movzx    r1d, word [rd422u+r6*2]
    xor      r4d, r4d
    cmp      r1d, 128
    seta     r4b
    movzx    r5d, byte [r8+%1]
    lea      r5d, [r5*2+r4]
    mov      r2d, r4d
    mov      r4d, [rd_sig_tab+r5*4 GLOBAL]
    mov [r8+%1], r4b
    shr      r4d, 16
    add      r0d, r4d
    movzx    r5d, byte [r8+%2]
    RD422_UNARY 5, 1
    mov [r8+%2], r5b
%endmacro

; the escape sum of the 8 abs-14 dwords in m6 (clobbered) to %1; m1, m7 clobbered, m3 = 0.
; The float exponent is floor(log2) below 2^24: 4:2:2 levels are below 2^(7+bit depth)
; and the C (bs_size_ue_big) only covers abs-15 < 65535.
%macro RD422_ESC_SUM 1
    cvtdq2ps  m7, m6
    psrld     m7, 23
    pslld     m7, 9
    vpbroadcastd m1, [rd422_k+4]
    paddd     m7, m1                                          ; (2*ilog2(abs-14)+1)<<8, exact below 2^24
    pxor      m3, m3
    pcmpgtd   m6, m3
    pand      m7, m6
    vextracti128 xm6, m7, 1
    paddd    xm7, xm6
    pshufd   xm6, xm7, q1032
    paddd    xm7, xm6
    pshufd   xm6, xm7, q2301
    paddd    xm7, xm6
    movd      %1, xm7
%endmacro

%macro CABAC_RESIDUAL_RD_422DC_AVX2 0
    %define rd422c rsp
    %define rd422u rsp+16
    cglobal cabac_block_residual_422_dc_rd_internal, 4,13,8,-32
%ifdef PIC
    lea     r11, [$$]
    %define GLOBAL +r11-$$
%else
    %define GLOBAL
%endif
%if HIGH_BIT_DEPTH
    pabsd     m6, [r0]
    vextracti128 xm1, m6, 1
    packssdw xm0, xm6, xm1                                    ; abs, saturated
%else
    pabsw    xm0, [r0]
    pmovzxwd  m6, xm0
%endif
; escapes: sum over abs >= 15 of bs_size_ue_big(abs-15)<<8 = (2*ilog2(abs-14)+1)<<8
    vpbroadcastd m7, [rd422_k+0]
    psubd     m6, m7                                          ; abs-14
    RD422_ESC_SUM r4d
; unary rows min(abs,15)*128
    pminuw   xm1, xm0, [rd422_w15]
    psllw    xm1, 7
    mova [rd422u], xm1
    packsswb xm0, xm0                                         ; abs bytes, saturated
    mova     xm5, [pb_1]
    pcmpeqb  xm2, xm0, xm5
    pcmpeqb  xm1, xm0, xm3
    pmovmskb r12d, xm2
    pmovmskb  r9d, xm1
    not       r9d
    movzx     r9d, r9b                                        ; bit i = l[i] != 0
    andn     r12d, r12d, r9d                                  ; bit i = abs(l[i]) > 1
    lzcnt     r6d, r9d
    xor       r6d, 31                                         ; r6 = last
; codes: sig = p <= last ? nz : 2, last = nz ? p == last : 2
    pminub   xm3, xm0, xm5                                    ; nz
    psrlq    xm4, xm3, 8
    por      xm4, xm3
    psrlq    xm1, xm4, 16
    por      xm4, xm1
    psrlq    xm1, xm4, 32
    por      xm4, xm1                                         ; p <= last
    psubb    xm1, xm5, xm4
    paddb    xm1, xm1
    paddb    xm1, xm3                                         ; sig codes
    psrlq    xm2, xm4, 8
    psubb    xm4, xm2                                         ; p == last
    psubb    xm2, xm5, xm3
    paddb    xm2, xm2
    paddb    xm2, xm4                                         ; last codes
    punpcklqdq xm1, xm2
    pshufb   xm1, [rd422_pairs]
    pmaddubsw xm1, [rd8_sig_pair]                             ; 3*c1+c2
    mova [rd422c], xm1
    RD422_BODY
%endmacro

; the scalar passes of the 4:2:2 dc rd kernels: in r1d b_interlaced, r2 ctx_block_cat,
; r3 cb, r4d the escape sum, r6 last, r9 nonzero mask, r12 levels > 1, the pair
; codes at rd422c and the unary rows at rd422u
%macro RD422_BODY 0
    shl      r1d, 4                                           ; MB_INTERLACED*16
    add      r1d, r2d
    movzx    r5d, word [significant_coeff_flag_offset+r1*2 GLOBAL]    ; r5 = ctx_sig
    movzx    r7d, word [last_coeff_flag_offset+r1*2 GLOBAL]           ; r7 = ctx_last
    movzx    r8d, word [coeff_abs_level_m1_offset+r2*2 GLOBAL]        ; r8 = ctx_level
    mov      r0d, [r3+cb.bits_encoded]                        ; r0 = cabac.f8_bits_encoded
    add      r0d, r4d
    add       r3, cb.state
    add       r5, r3
    add       r7, r3
    add       r8, r3
    xor     r10d, r10d
    RD422_CTX r5, 0, 0
    RD422_CTX r7, 0, 4
    cmp      r6d, 2
    jb .sig_end
    RD422_CTX r5, 1, 1
    RD422_CTX r7, 1, 5
    cmp      r6d, 4
    jb .sig_end
    RD422_CTX r5, 2, 2, 3
    RD422_CTX r7, 2, 6, 7
.sig_end:
    shr      r10, 17
    add      r0d, r10d
    popcnt   r4d, r9d                                         ; N
%if RD422_LEVELS_MIN > 1
    cmp      r4d, RD422_LEVELS_MIN
    jb .levels_coef
%endif
    RD422_LEVELS
.end:
    mov [r3+cb.bits_encoded-cb.state], r0d
    RET
%if RD422_LEVELS_MIN > 1
; levels per coefficient, descending, no branch on the level; node_ctx in r7
.levels_coef:
    btr      r9d, r6d
    RD422_LEVEL 1, 5
    lea      r7d, [r2*2+r2+1]                                 ; node_ctx 1 or 4
%rep RD422_LEVELS_MIN-2
    test     r9d, r9d
    jz .end
    lzcnt    r6d, r9d
    xor      r6d, 31
    btr      r9d, r6d
