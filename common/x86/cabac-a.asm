; %1 = 8x8 mode
; %2 = dct register
; %3 = countcat
; %4 = name
%macro SIGMAP_LOOP 3-4
.sigmap_%4loop:
%if HIGH_BIT_DEPTH
    mov      %2, [dct+r10*4]
%else
    movsx    %2, word [dct+r10*2]
%endif
%if %1
    movzx   r1d, byte [sigoff_8x8 + r10]
    add     r1d, sigoffd
%else
    lea     r1d, [sigoffd + r10d]
%endif
    test     %2, %2
    jz .sigmap_%4zero               ; if( l[i] )
    inc coeffidxd
    mov [coeffs+coeffidxq*4], %2    ; coeffs[++coeff_idx] = l[i];
    mov     r2d, 1
    CALL_CABAC                      ; x264_cabac_encode_decision( cb, ctx_sig + sig_off, 1 );
%if %1
    movzx   r1d, byte [last_coeff_flag_offset_8x8 + r10 GLOBAL]
    add     r1d, lastoffd
%else
    lea     r1d, [lastoffd + r10d]
%endif
    cmp    r10d, lastm              ; if( i == last )
    je .sigmap_%4last
    xor     r2d, r2d
    CALL_CABAC                      ; x264_cabac_encode_decision( cb, ctx_last + last_off, 0 );
    jmp .sigmap_%4loop_endcheck
.sigmap_%4zero:
    xor     r2d, r2d
    CALL_CABAC                      ; x264_cabac_encode_decision( cb, ctx_sig + sig_off, 0 );
.sigmap_%4loop_endcheck:
    inc    r10d
    cmp    r10d, %3
    jne .sigmap_%4loop              ; if( ++i == count_m1 )
%if HIGH_BIT_DEPTH
    mov      %2, [dct+r10*4]
%else
    movsx    %2, word [dct+r10*2]
%endif
    inc coeffidxd
    mov [coeffs+coeffidxq*4], %2    ; coeffs[++coeff_idx] = l[i]
    jmp .sigmap_%4end
.sigmap_%4last:                     ; x264_cabac_encode_decision( cb, ctx_last + last_off, 1 );
    mov     r2d, 1
    CALL_CABAC
.sigmap_%4end:
%if %1==0
    jmp .level_loop_start
%endif
%endmacro

%macro CABAC_RESIDUAL 1
cglobal cabac_block_residual_internal, 4,15,0,-4*64
%ifdef PIC
; if we use the same r7 as in cabac_encode_decision, we can cheat and save a register.
    lea     r7, [$$]
    %define lastm [rsp+4*1]
    %define GLOBAL +r7-$$
%else
    %define lastm r7d
    %define GLOBAL
%endif
    shl     r1d, 4

    %define sigoffq r8
    %define sigoffd r8d
    %define lastoffq r9
    %define lastoffd r9d
    %define leveloffq r10
    %define leveloffd r10d
    %define leveloffm [rsp+4*0]
    %define countcatd r11d
    %define sigoff_8x8 r12
    %define coeffidxq r13
    %define coeffidxd r13d
    %define dct r14
    %define coeffs rsp+4*2

    lea sigoff_8x8, [significant_coeff_flag_offset_8x8+r1*4 GLOBAL]
    add     r1d, r2d
    movzx sigoffd, word [significant_coeff_flag_offset+r1*2 GLOBAL]
    movzx lastoffd, word [last_coeff_flag_offset+r1*2 GLOBAL]
    movzx leveloffd, word [coeff_abs_level_m1_offset+r2*2 GLOBAL]
    movzx countcatd, byte [count_cat_m1+r2 GLOBAL]
    mov coeffidxd, -1
    mov     dct, r0
    mov leveloffm, leveloffd

    call [%1+gprsize*r2 GLOBAL]
    mov   lastm, eax
; put cabac in r0; needed for cabac_encode_decision
    mov      r0, r3

    xor    r10d, r10d
    cmp countcatd, 63
    je .sigmap_8x8
    SIGMAP_LOOP 0, r12d, countcatd,
.sigmap_8x8:
    SIGMAP_LOOP 1, r11d, 63, _8x8
.level_loop_start:
; we now have r8, r9, r11, r12, and r7/r14(dct) free for the main loop.
    %define nodectxq r8
    %define nodectxd r8d
    mov leveloffd, leveloffm
    xor nodectxd, nodectxd
.level_loop:
    mov     r9d, [coeffs+coeffidxq*4]
    mov    r11d, r9d
    sar    r11d, 31
    add     r9d, r11d
    movzx   r1d, byte [coeff_abs_level1_ctx+nodectxq GLOBAL]
    xor     r9d, r11d
    add     r1d, leveloffd
    cmp     r9d, 1
    jg .level_gt1
    xor     r2d, r2d
    CALL_CABAC
    movzx nodectxd, byte [coeff_abs_level_transition+nodectxq GLOBAL]
    jmp .level_sign
.level_gt1:
    mov     r2d, 1
    CALL_CABAC
    movzx  r14d, byte [coeff_abs_levelgt1_ctx+nodectxq GLOBAL]
    add    r14d, leveloffd
    cmp     r9d, 15
    mov    r12d, 15
    cmovl  r12d, r9d
    sub    r12d, 2
    jz .level_eq2
.level_gt1_loop:
    mov     r1d, r14d
    mov     r2d, 1
    CALL_CABAC
    dec    r12d
    jg .level_gt1_loop
    cmp     r9d, 15
    jge .level_bypass
.level_eq2:
    mov     r1d, r14d
    xor     r2d, r2d
    CALL_CABAC
    jmp .level_gt1_end
.level_bypass:
    lea     r2d, [r9d-15]
    xor     r1d, r1d
    push     r0
; we could avoid this if we implemented it in asm, but I don't feel like that
; right now.
%if UNIX64
    push     r7
    push     r8
%else
    sub      rsp, 32 ; shadow space
%endif
    call cabac_encode_ue_bypass
%if UNIX64
    pop      r8
    pop      r7
%else
    add      rsp, 32
%endif
    pop      r0
.level_gt1_end:
    movzx nodectxd, byte [coeff_abs_level_transition+8+nodectxq GLOBAL]
.level_sign:
    mov     r1d, r11d
    call cabac_encode_bypass_asm
%if WIN64
    mov      r0, r3
%endif
    dec coeffidxd
    jge .level_loop
    RET
%endmacro

;-----------------------------------------------------------------------------
; BMI2: low/range/queue stay in r8-r10 for the whole block; decision,
; bypass and putbyte are inlined. low is 64-bit and queue is biased by -24,
; so bytes are emitted 4 at a time and the rest at the end of the block.
;-----------------------------------------------------------------------------

; in: flags from the queue update; clobbers r1, r4-r6
; the no-flush path falls through, the flush is a per-site stub after RET
%macro PUTBYTE 0
    jge .pb %+ pb_count
.pbr %+ pb_count:
    %assign pb_count pb_count+1
%endmacro

; one stub per site: 4 bytes pending. last byte not 0xff and nothing
; outstanding: store all 4 inline, else .putbytes_slow
%macro PUTBYTE_STUBS 0
%assign pb_i 0
%rep pb_count
.pb %+ pb_i:
    mov      r6, cbm
    lea     r4d, [queueq+10]
    shrx     r1, lowq, r4           ; carry, 4 bytes
    cmp     r1b, 0xff
    je .pbs %+ pb_i
    cmp dword [r6+cb.bytes_outstanding], 0
    jne .pbs %+ pb_i
    bzhi   lowq, lowq, r4
    sub  queued, 32
    mov      r5, [r6+cb.p]
    rorx     r4, r1, 32             ; carry
    add  [r5-1], r4b
    bswap   r1d
    mov    [r5], r1d
    add      r5, 4
    mov [r6+cb.p], r5
    jmp .pbr %+ pb_i
.pbs %+ pb_i:
    call .putbytes_slow
    jmp .pbr %+ pb_i
%assign pb_i pb_i+1
%endrep
%endmacro

; %1 = bin, %2 = state address (else the state is in r2d)
; in: r2d = state if no %2; out: r2d = next state
; clobbers r1, r4-r6
%macro CABAC_BIN 1-2
%if %0 > 1
    movzx   r2d, byte [%2]
%endif
    mov     r4d, ranged
    mov     r5d, r2d
    shr     r4d, 6
    and     r5d, ~1
%ifdef PIC
    lea      r5, [r7+r5*2]
    movzx   r4d, byte [r5+r4+cabac_range_lps-4-$$]
%else
    movzx   r4d, byte [cabac_range_lps-4+r4+r5*2]
%endif
    sub  ranged, r4d
    lea      r6, [lowq+rangeq]
    test    r2b, 1
%if %1
    cmovz  ranged, r4d
    cmovz    lowq, r6
%else
    cmovnz ranged, r4d
    cmovnz   lowq, r6
%endif
    movzx   r2d, byte [cabac_transition+%1+r2*2 GLOBAL]
%if %0 > 1
    mov    [%2], r2b
%endif
    lzcnt   r5d, ranged
    sub     r5d, 23
    shlx ranged, ranged, r5d
    shlx   lowq, lowq, r5
    add  queued, r5d
    PUTBYTE
%endmacro

; %1 = 8x8 mode, %2 = count_m1
%macro SIGMAP_BMI2 2
%%loop:
%if cpuflag(avx512icl)
    bt      r14, r12                ; r14 = nonzero mask, coeffs[] already packed
    jnc %%zero
%else
%if HIGH_BIT_DEPTH
    mov     r1d, [r14+r12*4]
%else
    movsx   r1d, word [r14+r12*2]
%endif
    test    r1d, r1d
    jz %%zero                       ; if( l[i] )
    inc     r13d
    mov [coeffs+r13*4], r1d         ; coeffs[++coeff_idx] = l[i];
%endif
%if %1
    movzx   r1d, byte [r0+r12]
    CABAC_BIN 1, r3+r1              ; ctx_sig + sig_off, 1
%if %1 == 2
    movzx   r1d, byte [r0+r12]      ; 4:2:2 dc: last_off == sig_off
%else
    movzx   r1d, byte [last_coeff_flag_offset_8x8+r12 GLOBAL]
%endif
    %define sm_last r11+r1
%else
    CABAC_BIN 1, r3+r12
    %define sm_last r11+r12
%endif
    cmp     r12d, lastm             ; if( i == last )
    je %%is_last
    CABAC_BIN 0, sm_last            ; ctx_last + last_off, 0
    jmp %%next
%%zero:
%if %1
    movzx   r1d, byte [r0+r12]
    CABAC_BIN 0, r3+r1              ; ctx_sig + sig_off, 0
%else
    CABAC_BIN 0, r3+r12
%endif
%%next:
    inc     r12d
    cmp     r12d, %2
    jne %%loop                      ; if( ++i == count_m1 )
%if notcpuflag(avx512icl)
%if HIGH_BIT_DEPTH
    mov     r1d, [r14+r12*4]
%else
    movsx   r1d, word [r14+r12*2]
%endif
    inc     r13d
    mov [coeffs+r13*4], r1d         ; coeffs[++coeff_idx] = l[i]
%endif
    jmp .level_loop_start
%%is_last:
    CABAC_BIN 1, sm_last            ; ctx_last + last_off, 1
%if %1 == 0
    jmp .level_loop_start
%endif
%endmacro

; coeffs[r13]: words at avx512icl 8-bit (packed by vpcompressw), else dwords
%macro LOAD_COEFFS 1
%if cpuflag(avx512icl) && HIGH_BIT_DEPTH == 0
    movsx    %1, word [coeffs+r13*2]
%else
    mov      %1, [coeffs+r13*4]
%endif
%endmacro

; %2 = 4:2:2 chroma dc (cabac_block_residual_422_dc_internal, ctx_block_cat = DCT_CHROMA_DC)
%macro CABAC_RESIDUAL_BMI2 1-2 0
%if %2
cglobal cabac_block_residual_422_dc_internal, 4,15,0,-4*72
%else
cglobal cabac_block_residual_internal, 4,15,0,-4*72
%endif
%ifdef PIC
    lea      r7, [$$]
    %define GLOBAL +r7-$$
%else
    %define GLOBAL
%endif
    %define cbm    [rsp+0]
    %define levelm [rsp+8]
    %define lastm  [rsp+16]
    %define coeffs rsp+32
    %define lowd   r8d
    %define lowq   r8
    %define ranged r9d
    %define rangeq r9
    %define queued r10d
    %define queueq r10
    %assign pb_count 0

    shl     r1d, 4
%if %2
    lea     r12, [coeff_flag_offset_chroma_422_dc GLOBAL]
%else
    lea     r12, [significant_coeff_flag_offset_8x8+r1*4 GLOBAL]
%endif
    add     r1d, r2d
    movzx   r8d, word [significant_coeff_flag_offset+r1*2 GLOBAL]
    movzx   r9d, word [last_coeff_flag_offset+r1*2 GLOBAL]
    movzx  r10d, word [coeff_abs_level_m1_offset+r2*2 GLOBAL]
%if %2
    mov    r13d, 7
%else
    movzx  r13d, byte [count_cat_m1+r2 GLOBAL]
%endif
    mov     cbm, r3
    mov     r14, r0                 ; dct
    add      r3, cb.state
    lea     r11, [r3+r9]            ; ctx_last state
    add     r10, r3
    mov  levelm, r10                ; ctx_level state
    add      r3, r8                 ; ctx_sig state
%if cpuflag(avx512icl)
; nonzero mask (r14), last, and coeffs[] = the nonzero coefs ascending
; (vpcompress register form + full stores), r13 = their count - 1
    lea     r1d, [r13+1]
    cmp    r13d, 63
    je .mask_8x8
    mov     r6d, -1
    bzhi    r6d, r6d, r1d
    kmovw    k1, r6d
%if HIGH_BIT_DEPTH
    vmovdqu32 zmm16 {k1}{z}, [r14]
    vptestmd  k1, zmm16, zmm16
    vpcompressd zmm16 {k1}{z}, zmm16
    vmovdqu32 [coeffs], zmm16
%else
    vmovdqu16 ymm16 {k1}{z}, [r14]
    vptestmw  k1, ymm16, ymm16
    vpcompressw ymm16 {k1}{z}, ymm16
    vmovdqu16 [coeffs], ymm16
%endif
    kmovw   r14d, k1
    jmp .mask_done
.mask_8x8:
%if HIGH_BIT_DEPTH
    vmovdqu32 zmm16, [r14+0*64]
    vmovdqu32 zmm17, [r14+1*64]
    vmovdqu32 zmm18, [r14+2*64]
    vmovdqu32 zmm19, [r14+3*64]
    vptestmd  k1, zmm16, zmm16
    vptestmd  k2, zmm17, zmm17
    vptestmd  k3, zmm18, zmm18
    vptestmd  k4, zmm19, zmm19
    vpcompressd zmm16 {k1}{z}, zmm16
    vpcompressd zmm17 {k2}{z}, zmm17
    vpcompressd zmm18 {k3}{z}, zmm18
    vpcompressd zmm19 {k4}{z}, zmm19
    kmovw    r4d, k1
    kmovw    r5d, k2
    kmovw    r6d, k3
    popcnt   r4d, r4d
    popcnt   r5d, r5d
    popcnt   r6d, r6d
    add      r5d, r4d
    add      r6d, r5d
    vmovdqu32 [coeffs], zmm16
    vmovdqu32 [coeffs+r4*4], zmm17
    vmovdqu32 [coeffs+r5*4], zmm18
    vmovdqu32 [coeffs+r6*4], zmm19
    kunpckwd  k1, k2, k1
    kunpckwd  k3, k4, k3
    kunpckdq  k1, k3, k1
%else
    vmovdqu16 zmm16, [r14+0*64]
    vmovdqu16 zmm17, [r14+1*64]
    vptestmw  k1, zmm16, zmm16
    vptestmw  k2, zmm17, zmm17
    vpcompressw zmm16 {k1}{z}, zmm16
    vpcompressw zmm17 {k2}{z}, zmm17
    kmovd    r4d, k1
    popcnt   r4d, r4d
    vmovdqu16 [coeffs], zmm16
    vmovdqu16 [coeffs+r4*2], zmm17
    kunpckdq  k1, k2, k1
%endif
    kmovq    r14, k1
.mask_done:
    popcnt   r1, r14
    lea     r13d, [r1-1]            ; coeff_idx
    lzcnt    r1, r14
    xor     r1d, 63
    mov   lastm, r1d
%else
    call [%1+gprsize*r2 GLOBAL]     ; preserves r3, r7-r14
    mov   lastm, eax
%endif
    mov      r6, cbm
    mov    lowd, [r6+cb.low]
    mov  ranged, [r6+cb.range]
    mov  queued, [r6+cb.queue]
    sub  queued, 24
%if %2
    mov      r0, r12
    xor    r12d, r12d
    SIGMAP_BMI2 2, 7
%elif cpuflag(avx512icl)
    movzx   r0d, byte [count_cat_m1+r2 GLOBAL]
    cmp     r0d, 63
    je .sigmap_8x8
    xor    r12d, r12d               ; i
    SIGMAP_BMI2 0, r0d
.sigmap_8x8:
    mov      r0, r12
    xor    r12d, r12d
    SIGMAP_BMI2 1, 63
%else
    cmp    r13d, 63
    je .sigmap_8x8
    mov     r0d, r13d
    mov    r13d, -1                 ; coeff_idx
    xor    r12d, r12d               ; i
    SIGMAP_BMI2 0, r0d
.sigmap_8x8:
    mov      r0, r12
    mov    r13d, -1
    xor    r12d, r12d
    SIGMAP_BMI2 1, 63
%endif
.level_loop_start:
    mov      r3, levelm
    xor    r12d, r12d               ; node_ctx
.level_loop:
    LOAD_COEFFS r11d
    mov     r1d, r11d
    sar     r1d, 31
    add    r11d, r1d
    xor    r11d, r1d                ; abs_coeff
    movzx   r1d, byte [coeff_abs_level1_ctx+r12 GLOBAL]
    cmp    r11d, 1
    jg .level_gt1
    CABAC_BIN 0, r3+r1
    movzx  r12d, byte [coeff_abs_level_transition+r12 GLOBAL]
    jmp .level_sign
.level_gt1:
    CABAC_BIN 1, r3+r1
%if %2
    movzx  r14d, byte [coeff_abs_levelgt1_ctx_chroma_dc+r12 GLOBAL]
%else
    movzx  r14d, byte [coeff_abs_levelgt1_ctx+r12 GLOBAL]
%endif
    movzx   r2d, byte [r3+r14]      ; state stays in r2d for the run
    mov     r0d, 15
    cmp    r11d, r0d
    cmovl   r0d, r11d
    sub     r0d, 2
    jz .level_eq2
.level_gt1_loop:
    CABAC_BIN 1
    dec     r0d
    jg .level_gt1_loop
    cmp    r11d, 15
    jge .level_bypass
.level_eq2:
    CABAC_BIN 0
    mov [r3+r14], r2b
    jmp .level_gt1_end
.level_bypass:
    mov [r3+r14], r2b
; x264_cabac_encode_ue_bypass( cb, 0, abs_coeff - 15 )
    lea     r0d, [r11-14]           ; v
    lzcnt  r11d, r0d
    xor    r11d, 31                 ; k
    lea    r14d, [r11*2+1]          ; bits left
    mov     r2d, 3
    shlx    r2d, r2d, r11d
    sub     r0d, r2d
    mov     r2d, 1
    shlx    r2d, r2d, r14d
    add     r2d, r0d                ; x = v + bypass_lut[k]
    lea    r11d, [r14-1]
    and    r11d, 7
    inc    r11d                     ; i
.ue_loop:
    sub    r14d, r11d
    shrx    r1d, r2d, r14d
    movzx   r1d, r1b
    imul    r1d, ranged
    shlx   lowq, lowq, r11
    add    lowq, r1
    add  queued, r11d
    PUTBYTE
    mov    r11d, 8
    test   r14d, r14d
    jg .ue_loop
.level_gt1_end:
    movzx  r12d, byte [coeff_abs_level_transition+8+r12 GLOBAL]
.level_sign:
; x264_cabac_encode_bypass( cb, coeff_sign )
    LOAD_COEFFS r1d
    sar     r1d, 31
    and     r1d, ranged
    lea     lowq, [lowq*2+r1]
    inc  queued
    PUTBYTE
    dec    r13d
    jge .level_loop
; emit the 0-3 whole bytes left, store the state unbiased
    mov      r6, cbm
    lea     r0d, [queueq+32]        ; pending bits
    mov     r4d, r0d
    and     r0d, 7
    add     r0d, 10                 ; lowest bit of the whole bytes
    shr     r4d, 3                  ; n
    shrx     r1, lowq, r0           ; carry, n bytes
    cmp     r1b, 0xff
    je .flush_slow
    cmp dword [r6+cb.bytes_outstanding], 0
    jne .flush_slow
    bzhi   lowq, lowq, r0
    lea     r2d, [r4*8]
    sub  queued, r2d
    neg     r2d
    add     r2d, 32
    shlx     r1, r1, r2             ; carry in bit 32, bytes from bit 31 down
    mov      r5, [r6+cb.p]
    rorx     r2, r1, 32
    add  [r5-1], r2b
    bswap   r1d
    mov    [r5], r1d                ; 4-n bytes past p are rewritten later
    add      r5, r4
    mov [r6+cb.p], r5
.flush_end:
    add  queued, 24
    mov [r6+cb.low], lowd
    mov [r6+cb.range], ranged
    mov [r6+cb.queue], queued
    RET
.flush_slow:
    call .putbytes_slow
    mov      r6, cbm
    jmp .flush_end

; x264_cabac_putbyte while queue >= 0; in: r6 = cb; clobbers r1, r4-r6
.putbytes_slow:
    mov     r4d, [r6+cb.bytes_outstanding]
    mov      r5, [r6+cb.p]
    jmp .slow_next
.slow_loop:
    lea     r6d, [queueq+34]
    shrx     r1, lowq, r6           ; out
    bzhi   lowq, lowq, r6
    sub  queued, 8
    cmp     r1b, 0xff
    je .postpone
    mov     r6d, r1d
    shr     r6d, 8                  ; carry
    add  [r5-1], r6b
    dec     r6d
    test    r4d, r4d
    jz .write
.loop_outstanding:
    mov    [r5], r6b
    inc      r5
    dec     r4d
    jg .loop_outstanding
.write:
    mov    [r5], r1b
    inc      r5
    jmp .slow_next
.postpone:
    inc     r4d
.slow_next:
    cmp  queued, -24
    jge .slow_loop
    mov      r6, [rsp+gprsize]
    mov [r6+cb.p], r5
    mov [r6+cb.bytes_outstanding], r4d
    ret

    PUTBYTE_STUBS
%endmacro

