;-----------------------------------------------------------------------------
; BMI2: low/range/queue stay in r8-r10 for the whole block; decision,
; bypass and putbyte are inlined. low is 64-bit and queue is biased by -24,
; so bytes are emitted 4 at a time and the rest at the end of the block.
;-----------------------------------------------------------------------------

; in: flags from the queue update; clobbers r1, r4-r6
; the no-flush path falls through, the flush is a per-site stub after RET
%macro PUTBYTE 0
    jge .pb %+ pb_count
.pbr %+ pb_count:
    %assign pb_count pb_count+1
%endmacro

; one stub per site: 4 bytes pending. last byte not 0xff and nothing
; outstanding: store all 4 inline, else .putbytes_slow
%macro PUTBYTE_STUBS 0
%assign pb_i 0
%rep pb_count
.pb %+ pb_i:
    mov      r6, cbm
    lea     r4d, [queueq+10]
    shrx     r1, lowq, r4           ; carry, 4 bytes
    cmp     r1b, 0xff
    je .pbs %+ pb_i
    cmp dword [r6+cb.bytes_outstanding], 0
    jne .pbs %+ pb_i
    bzhi   lowq, lowq, r4
    sub  queued, 32
    mov      r5, [r6+cb.p]
    rorx     r4, r1, 32             ; carry
    add  [r5-1], r4b
    bswap   r1d
    mov    [r5], r1d
    add      r5, 4
    mov [r6+cb.p], r5
    jmp .pbr %+ pb_i
.pbs %+ pb_i:
    call .putbytes_slow
    jmp .pbr %+ pb_i
%assign pb_i pb_i+1
%endrep
%endmacro

; %1 = bin, %2 = state address (else the state is in r2d)
; in: r2d = state if no %2; out: r2d = next state
; clobbers r1, r4-r6
%macro CABAC_BIN 1-2
%if %0 > 1
    movzx   r2d, byte [%2]
%endif
    mov      r5, [cabac_lps_trans+r2*8 GLOBAL] ; off the range chain
    mov     r4d, ranged
    and     r4d, 0xc0
    shr     r4d, 3
    shrx    r4d, r5d, r4d
    movzx   r4d, r4b                ; range_lps
    sub  ranged, r4d
    lea      r6, [lowq+rangeq]
    test    r2b, 1
%if %1
    cmovz  ranged, r4d
    cmovz    lowq, r6
%else
    cmovnz ranged, r4d
    cmovnz   lowq, r6
%endif
    movzx   r2d, byte [cabac_lps_trans+4+%1+r2*8 GLOBAL]
%if %0 > 1
    mov    [%2], r2b
%endif
    lzcnt   r5d, ranged
    sub     r5d, 23
    shlx ranged, ranged, r5d
    shlx   lowq, lowq, r5
    add  queued, r5d
    PUTBYTE
%endmacro

; %1 = 8x8 mode, %2 = count_m1
%macro SIGMAP_BMI2 2
