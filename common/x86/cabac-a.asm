    movzx    r3d, byte [r5+r2]
    bt        r9, r1
    adc      r3d, r3d                                         ; 2*state+bin
    movzx   r10d, byte [cabac_transition+r3 GLOBAL]
    movzx    r3d, word [rd_entropy_sb+r3*2 GLOBAL]
