    shl      r1d, 4                                           ; MB_INTERLACED*16
    add      r1d, r2d
    movzx    r5d, word [significant_coeff_flag_offset+r1*2 GLOBAL]    ; r5 = ctx_sig
    movzx    r7d, word [last_coeff_flag_offset+r1*2 GLOBAL]           ; r7 = ctx_last
    movzx    r8d, word [coeff_abs_level_m1_offset+r2*2 GLOBAL]        ; r8 = ctx_level
    movzx    r9d, byte [count_cat_m1+r2 GLOBAL]
    mov      r0d, [r3+cb.bits_encoded]                        ; r0 = cabac.f8_bits_encoded
    add       r3, cb.state
    add       r5, r3
    add       r7, r3
    add       r8, r3
    kmovd    r4d, k2                                          ; r4 = nonzero mask
    lzcnt    r6d, r4d
    xor      r6d, 31                                          ; r6 = last
; sig flags for i <= last, except last == count_m1
    cmp      r6d, r9d
    mov      r1d, r6d
    adc      r1d, 0
    mov      r9d, -1
    bzhi     r9d, r9d, r1d
; last flags for the nonzero ones among them
    mov      r1d, r4d
    and      r1d, r9d
    shl      r1d, 16
    or       r1d, r9d
    kmovd    k3, r1d                                          ; coded lanes: sig 0-15, last 16-31
; bins: sig = l[i] != 0, last = i == last
    lea      r1d, [r6+16]
    mov      r9d, r4d
    bts      r9d, r1d
    kmovd    k4, r9d
    vmovdqu8 xm1, [r5]
    vinserti32x4 ym1, ym1, [r7], 1                            ; states
    vpmovm2b ym2, k4
    vpternlogd ym2, ym1, [pb_1], 0x6c                         ; state^bin
    vmovdqu8 zm3, [rd_entropy_lo]
    vpermt2b zm3 {k3}{z}, zm2, [rd_entropy_lo+64]
    vmovdqu8 zm4, [rd_entropy_hi]
    vpermt2b zm4 {k3}{z}, zm2, [rd_entropy_hi+64]
    vmovdqu8 zm5, [rd_transition_xor]
    vpermt2b zm5, zm2, [rd_transition_xor+64]
    vpternlogd ym5, ym1, [pb_1], 0x78                         ; transition[state][bin]
    vmovdqu8 ym1 {k3}, ym5
    vmovdqu8 [r5], xm1
    vextracti32x4 [r7], ym1, 1
    vpxord   xm6, xm6, xm6
    vpsadbw  ym3, ym3, ym6
    vpsadbw  ym4, ym4, ym6
    vpsllq   ym4, ym4, 8
    vpaddq   ym3, ym3, ym4
    vextracti32x4 xm4, ym3, 1
    vpaddq   xm3, xm3, xm4
    vpsrldq  xm4, xm3, 8
    vpaddq   xm3, xm3, xm4
    vmovd    r1d, xm3
    add      r0d, r1d
; levels: last, then the other nonzero coefficients in descending order
    LOAD_DCTCOEF r1d
    COEFF_ABS_LEVEL_GT1 last, 1
    btr      r4d, r6d
    test     r4d, r4d
    jz .end
.level_loop:
    lzcnt    r6d, r4d
    xor      r6d, 31
    btr      r4d, r6d
    LOAD_DCTCOEF r1d
    COEFF_ABS_LEVEL_GT1 coeff, 0
    test     r4d, r4d
    jnz .level_loop
.end:
    mov [r3+cb.bits_encoded-cb.state], r0d
    RET
%endmacro

; 4:2:2 chroma dc, avx512icl (ctx_block_cat = DCT_CHROMA_DC, 8 coefficients).
; The sig and last contexts repeat (0,0,1,1,2,2,2), so the sig flags are coded
; serially, descending; the last flags below last are all bin 0: per context n
; from popcnt and one rd8_last_pow/bits step. Levels as in the 4x4 icl kernel,
; with the chroma dc gt1 contexts (capped at 8).
%macro CABAC_RESIDUAL_RD_422DC_ICL 0
    %assign rd422_stack 16*SIZEOF_DCTCOEF+32 ; abs() copy, level contexts
%ifdef PIC
    cglobal cabac_block_residual_422_dc_rd_internal, 4,12,8,-rd422_stack
    lea     r10, [$$]
    %define GLOBAL +r10-$$
%else
    cglobal cabac_block_residual_422_dc_rd_internal, 4,12,8,-rd422_stack
    %define GLOBAL
%endif
    RD_TMP_REGS 5, 7, 9
    %define dct rsp
    %define ctx1m  rsp+16*SIZEOF_DCTCOEF
    %define ctxg1m rsp+16*SIZEOF_DCTCOEF+16
%if HIGH_BIT_DEPTH
    vmovdqu32 ym0, [r0]
    vptestmd  k2, ym0, ym0
    vpabsd    ym0, ym0
    vmovdqu32 [rsp], ym0
%else
    vmovdqu16 xm0, [r0]
    vptestmw  k2, xm0, xm0
    vpabsw    xm0, xm0
    vmovdqu16 [rsp], xm0
%endif
    shl      r1d, 4                                           ; MB_INTERLACED*16
    add      r1d, r2d
    movzx    r5d, word [significant_coeff_flag_offset+r1*2 GLOBAL]    ; r5 = ctx_sig
    movzx    r7d, word [last_coeff_flag_offset+r1*2 GLOBAL]           ; r7 = ctx_last
    movzx    r8d, word [coeff_abs_level_m1_offset+r2*2 GLOBAL]        ; r8 = ctx_level
    mov      r0d, [r3+cb.bits_encoded]
    add       r3, cb.state
    add       r5, r3
    add       r7, r3
    add       r8, r3
    kmovd    r4d, k2                                          ; r4 = nonzero mask
    lzcnt    r6d, r4d
    xor      r6d, 31                                          ; r6 = last
    cmp      r6d, 7
    je .skip_last
    movzx    r1d, byte [coeff_flag_offset_chroma_422_dc+r6 GLOBAL]
    movzx    r2d, byte [r5+r1]
    movzx    r9d, byte [cabac_transition+1+r2*2 GLOBAL]
    xor      r2d, 1
    movzx    r2d, word [cabac_entropy+r2*2 GLOBAL]
    mov [r5+r1], r9b
    add      r0d, r2d
    movzx    r2d, byte [r7+r1]
    movzx    r9d, byte [cabac_transition+1+r2*2 GLOBAL]
    xor      r2d, 1
    movzx    r2d, word [cabac_entropy+r2*2 GLOBAL]
    mov [r7+r1], r9b
    add      r0d, r2d
.skip_last:
; sig flags of i < last, descending
    lea      r1d, [r6-1]
    test     r1d, r1d
    jl .sig_done
.sig_loop:
    movzx    r2d, byte [coeff_flag_offset_chroma_422_dc+r1 GLOBAL]
    movzx    r9d, byte [r5+r2]
    bt       r4d, r1d
    adc      r9d, r9d                                         ; 2*state+bin
    movzx   r11d, byte [cabac_transition+r9 GLOBAL]
    movzx    r9d, word [rd_entropy_sb+r9*2 GLOBAL]
    mov [r5+r2], r11b
    add      r0d, r9d
    dec      r1d
    jge .sig_loop
.sig_done:
; last flags (bin 0) of the nonzero coefs below last, contexts 0-2
    mov      r1d, r4d
    btr      r1d, r6d
%assign %%c 0
%rep 3
    %if %%c == 0
        mov     r2d, 0x03
    %elif %%c == 1
        mov     r2d, 0x0c
    %else
        mov     r2d, 0x70
    %endif
    and      r2d, r1d
    popcnt   r2d, r2d
    shl      r2d, 7
    movzx    r9d, byte [r7+%%c]
    add      r2d, r9d                                         ; n*128+state
    movzx    r9d, byte [rd8_last_pow+r2 GLOBAL]
    mov [r7+%%c], r9b
    movzx    r9d, word [rd8_last_bits+r2*2 GLOBAL]
    add      r0d, r9d
    %assign %%c %%c+1
%endrep
; level contexts: ctx1 = g ? 0 : min(e,3)+1, ctxgt1 = min(g+5,8)
%if HIGH_BIT_DEPTH
    vpcmpud   k5, ym0, [pd_1] {1to8}, 6
%else
    vpcmpuw   k5, xm0, [pw_1], 6
%endif
    kmovd    r1d, k5
    andn     r2d, r1d, r4d
    vpbroadcastd ym1, r1d
    vpbroadcastd ym2, r2d
    vpsrlvd   ym1, ym1, [rd4_above]
    vpsrlvd   ym2, ym2, [rd4_above]
    vpopcntd  ym1, ym1                                        ; g
    vpopcntd  ym2, ym2                                        ; e
    vptestnmd k5, ym1, ym1
    vpminud   ym2, ym2, [rd4_ctxc+4] {1to8}
    vpaddd    ym2 {k5}{z}, ym2, [rd4_ctxc] {1to8}
    vpaddd    ym1, ym1, [rd4_ctxc+8] {1to8}
    vpminud   ym1, ym1, [rd4_ctx8] {1to8}
    vpmovdb  xm2, ym2
    vpmovdb  xm1, ym1
    vmovq    [ctx1m], xm2
    vmovq    [ctxg1m], xm1
; levels: last, then the other nonzero coefficients in descending order
.level_loop:
    lzcnt    r6d, r4d
    xor      r6d, 31
    btr      r4d, r6d
    LOAD_DCTCOEF r1d
    COEFF_ABS_LEVEL_GT1_ICL
    test     r4d, r4d
    jnz .level_loop
    mov [r3+cb.bits_encoded-cb.state], r0d
    RET
%endmacro

