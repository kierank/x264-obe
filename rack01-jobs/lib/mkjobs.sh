#!/bin/bash
# Copyright (C) 2026 Open Broadcast Systems Ltd
# rack01-jobs/lib/mkjobs.sh: every <pkg>/<job>.conf + lib/engine.sh -> <pkg>/<job>.sh, a standalone script.
# Run from anywhere: bash rack01-jobs/lib/mkjobs.sh
set -e
D=$(cd "$(dirname "$0")/.." && pwd)
for c in "$D"/*/*.conf; do
    s=${c%.conf}.sh
    {
        echo '#!/bin/bash'
        echo "# GENERATED by rack01-jobs/lib/mkjobs.sh from $(basename "$(dirname "$c")")/$(basename "$c") + lib/engine.sh: edit those, not this file."
        cat "$c"
        echo
        cat "$D/lib/engine.sh"
    } > "$s"
    chmod +x "$s"
    bash -n "$s"
    echo "$s"
done
